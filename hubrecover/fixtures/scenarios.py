"""Labelled synthetic source simulator. Exact dispatch records are frozen before search."""
from dataclasses import dataclass
from .reference import build_reference
from hubrecover.domain.schemas import SeedSnapshot
from hubrecover.domain.allocation import DispatchEvidence, Position
from hubrecover.domain.gate import RestrictionWindow
from hubrecover.domain.invariants import MINUTE
from hubrecover.domain.planning import materialize, operation_key
from hubrecover.domain.universe import Descriptor, select_descriptors

CASES = [
 ('happy', 'Complete recovery'), ('edit', 'Protect the international connection'),
 ('near_miss', 'Exactly 60 minutes: no trigger'), ('lifecycle', 'Brief lift and recurrence'),
 ('policy', 'Crew duty rejection'), ('no_viable', 'No viable option'),
 ('missing', 'Required source unavailable'), ('unauthorized', 'Approval boundary'),
 ('compensation', 'Compensation is outside scope'), ('injection', 'Untrusted source instructions'),
 ('limited', 'Limited precedent'), ('budget', 'Reject and exhaust regeneration budget'),
 ('partial', 'Booking and communication failure'), ('prerequisite', 'Missing operational acknowledgement'),
 ('stale', 'Stale plan and inventory race'), ('continuity', 'Continuity and dispatch checks'),
 ('contact', 'Missing passenger contact'), ('ranking', 'Passenger-aware ranking')]

@dataclass
class Scenario:
    name: str
    seed: SeedSnapshot
    current: list
    restrictions: list
    roots: list
    positions: list
    sources_verified: bool
    dispatch_records: dict
    def dispatch_for(self, flights):
        return [self.dispatch_records[operation_key(f)] for f in flights if operation_key(f) in self.dispatch_records]


def create_scenario(name='happy'):
    if name not in dict(CASES):
        raise ValueError('Unknown demonstration scenario')
    seed = build_reference()
    if name == 'contact':
        raw = seed.model_dump()
        raw['passengers'][0]['contact_available'] = False
        seed = SeedSnapshot.model_validate(raw)
    roots = [f.id for f in seed.flights if f.id.startswith('SYN-F-0-1-')]
    # Known estimated delay of the inbound aircraft; originals remain the passenger baseline.
    current = materialize(seed, seed.flights, Descriptor('DELAY', (roots[0],), 30))
    start = seed.day_start_ms
    restrictions = [RestrictionWindow(id='SYN-AUTHORITY-001', kind='GROUND_STOP', movement='DEPARTURE',
        applicable_flight_ids=[roots[0]], effective_ms=start+5*60*MINUTE,
        confirmed_end_ms=start+(6*60+30)*MINUTE, forecast_end_ms=None)]
    parties = {p.party_id: p for p in seed.passengers}
    flights = {f.id: f for f in seed.flights}
    positions = [Position(party_id=pid, airport_id=flights[p.itinerary[0]].origin,
                          ready_ms=start+6*60*MINUTE, completed_prefix=[]) for pid, p in parties.items()]
    records = {}
    # This models an immutable read-only dispatch source for the finite synthetic universe.
    # Never generated by a model, user text, or a later approval.
    for descriptor in select_descriptors(roots, {}).selected:
        for f in materialize(seed, current, descriptor):
            records[operation_key(f)] = DispatchEvidence(flight_id=f.id, departure_ms=f.departure_ms,
                arrival_ms=f.arrival_ms, tail_id=f.tail_id, crew_id=f.crew_id,
                status='UNKNOWN' if name == 'no_viable' else 'VERIFIED',
                route_compatible=True, fuel_compatible=True, restriction_compatible=True)
    return Scenario(name, seed, current, restrictions, roots, positions, name != 'missing', records)
